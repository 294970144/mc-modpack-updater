'use strict';
/**
 * 把 tools/diffplan-baseline.json 自动誊进
 * winui/tests/McUpdater.Tests/RealDiffPlanBaseline.cs。
 *
 * 与 tools/sync-real-baseline.js / sync-pcl2-baseline.js 同一条铁律：
 * 基准只能由 Node 原版实跑得出，誊写也必须由脚本完成 —— 手抄必错。
 *
 * 用法：node tools/gen-diffplan-baseline.js > tools/diffplan-baseline.json
 *       node tools/sync-diffplan-baseline.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const b = JSON.parse(fs.readFileSync(path.join(ROOT, 'tools', 'diffplan-baseline.json'), 'utf8'));
const dest = path.join(ROOT, 'winui', 'tests', 'McUpdater.Tests', 'RealDiffPlanBaseline.cs');

function cs(s) {
  return s === null || s === undefined ? 'null' : '@"' + String(s).replace(/"/g, '""') + '"';
}
const csBool = (x) => (x ? 'true' : 'false');

const L = [];
L.push('// <auto-generated>');
L.push('#nullable enable');
L.push('//   由 tools/sync-diffplan-baseline.js 从 tools/diffplan-baseline.json 誊写，请勿手改。');
L.push('//   基准来源：Node 原版 src/router.js 的 runDiff 在本机真实样本上实跑。');
L.push('// </auto-generated>');
L.push('');
L.push('namespace McUpdater.Tests;');
L.push('');
L.push('/// <summary>');
L.push('/// M5 真实环境基准：完整对比链路（四个分类全开）。');
L.push('/// 全部由 Node 原版实跑得出，经本脚本誊写 —— 手写必然出错。');
L.push('/// </summary>');
L.push('internal static class RealDiffPlanBaseline');
L.push('{');
L.push(`    /// <summary>基准是否可用（样本不在本机时为 false，测试整组跳过）。</summary>`);
L.push(`    public const bool Available = ${csBool(b.total > 0)};`);
L.push('');
L.push(`    public const string PackPath = ${cs(b.pack)};`);
L.push(`    public const string TargetDir = ${cs(b.targetDir)};`);
L.push('');
L.push('    /// <summary>');
L.push('    /// 生成基准时目标目录里的 jar 数。玩家装/删 mod 会让整套对比结果漂移，');
L.push('    /// 测试据此判断"环境未变" —— 变了就跳过而不是误报。');
L.push('    /// </summary>');
L.push(`    public const int TargetJarCount = ${b.targetJarCount};`);
L.push('');
L.push('    /// <summary>参与对比的分类（顺序即 Node 的 config.MANAGED_CATEGORIES 顺序）。</summary>');
L.push('    public static readonly string[] Categories =');
L.push('    [');
for (const c of b.categories) L.push(`        ${cs(c)},`);
L.push('    ];');
L.push('');
L.push('    /// <summary>变更条数（含无变化）。</summary>');
L.push(`    public const int Total = ${b.total};`);
L.push(`    public const int Conflicts = ${b.conflicts};`);
L.push('');
if (b.summary) {
  L.push('    /// <summary>Node runDiff 算出的 summary。</summary>');
  L.push(`    public const int Added = ${b.summary.added};`);
  L.push(`    public const int Updated = ${b.summary.updated};`);
  L.push(`    public const int Removed = ${b.summary.removed};`);
  L.push(`    public const int Unchanged = ${b.summary.unchanged};`);
  L.push(`    public const int Changed = ${b.summary.changed};`);
  L.push(`    public const long Bytes = ${b.summary.bytes};`);
  L.push(`    public const string BytesText = ${cs(b.summary.bytesText)};`);
  L.push(`    public const int PlayerInstalledRemovals = ${b.summary.playerInstalledRemovals};`);
  L.push(`    public const bool FirstRun = ${csBool(b.summary.firstRun)};`);
  L.push(`    public const int SkippedProtected = ${b.summary.skippedProtected};`);
  L.push(`    public const int SkippedOversize = ${b.summary.skippedOversize};`);
  L.push('    /// <summary>被跳过文件的样本（Node 最多留 8 条）。</summary>');
  L.push('    public static readonly string[] SkippedSamples =');
  L.push('    [');
  for (const s of b.summary.skippedSamples || []) L.push(`        ${cs(s)},`);
  L.push('    ];');
  L.push('');
}
L.push('    /// <summary>前 40 条变更的顺序基准：<c>type|category|key|fileName|checked</c>。</summary>');
L.push('    public static readonly string[] Head =');
L.push('    [');
for (const h of b.head) L.push(`        ${cs(h)},`);
L.push('    ];');
L.push('}');
L.push('');

fs.writeFileSync(dest, L.join('\n'), 'utf8');
process.stderr.write(`已写入基准：total=${b.total} head=${b.head.length}\n`);
