'use strict';
/**
 * 把 tools/pcl2-baseline.json 自动誊进
 * winui/tests/McUpdater.Tests/RealTargetBaseline.cs。
 *
 * 【为什么要自动生成而不是手抄】与 tools/sync-real-baseline.js 同一条铁律：
 * M2 那轮 106 条手抄基准错了 2 处，测试从此变成「验证错误期望」——
 * 比没有测试更糟。基准只能由 Node 原版实跑得出，誊写也必须由脚本完成。
 *
 * 用法：node tools/gen-pcl2-baseline.js > tools/pcl2-baseline.json
 *       node tools/sync-pcl2-baseline.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const baseline = JSON.parse(fs.readFileSync(path.join(ROOT, 'tools', 'pcl2-baseline.json'), 'utf8'));
const dest = path.join(ROOT, 'winui', 'tests', 'McUpdater.Tests', 'RealTargetBaseline.cs');

/** 转成 C# 逐字字符串字面量（只处理双引号，" 要写成 ""） */
function cs(s) {
  return s === null || s === undefined ? 'null' : '@"' + String(s).replace(/"/g, '""') + '"';
}
function csNullable(s) {
  return s === null || s === undefined ? 'null' : cs(s);
}
function csBool(b) {
  return b ? 'true' : 'false';
}
function csArr(arr) {
  return '[' + arr.join(', ') + ']';
}

const L = [];
L.push('// <auto-generated>');
// 生成的文件不继承项目的 <Nullable>enable</Nullable>，不加这行会给 CS8669
L.push('#nullable enable');
L.push('//   由 tools/sync-pcl2-baseline.js 从 tools/pcl2-baseline.json 誊写，请勿手改。');
L.push('//   基准来源：Node 原版 src/services/pcl2-detector.js + client-scanner.js 在本机实跑。');
L.push('// </auto-generated>');
L.push('');
L.push('namespace McUpdater.Tests;');
L.push('');
L.push('internal sealed record RealFolder(string Name, string Path, string Source, bool IsSelected);');
L.push('');
L.push('internal sealed record RealVersion(string Name, string FolderName, string FolderPath,');
L.push('    string ContentDir, bool Isolated, string IsolationBasis, string? GameVersion,');
L.push('    string? Loader, string? LoaderVersion, bool IsSelected, bool FolderSelected,');
L.push('    int ModCount, bool Managed);');
L.push('');
L.push('internal sealed record RealRank(string Name, string FolderName, string ContentDir, int Score, string[] Why);');
L.push('');
L.push('/// <summary>');
L.push('/// M4 真实环境基准：PCL2 探测 / 版本扫描 / 目标匹配。');
L.push('/// 全部由 Node 原版实跑得出，经本脚本誊写 —— 手写必然出错。');
L.push('/// </summary>');
L.push('internal static class RealTargetBaseline');
L.push('{');
L.push(`    public const string PackPath = ${cs(baseline.pack)};`);
L.push(`    public const string Pcl2Root = ${cs(baseline.root)};`);
L.push('');
L.push('    /// <summary>整合包元信息（matchTarget 的输入）。</summary>');
L.push(`    public const string PackName = ${cs(baseline.packMeta && baseline.packMeta.packName)};`);
L.push(`    public const string PackVersion = ${cs(baseline.packMeta && baseline.packMeta.packVersion)};`);
L.push(`    public const string VersionName = ${cs(baseline.packMeta && baseline.packMeta.versionName)};`);
L.push(`    public const string GameVersion = ${cs(baseline.packMeta && baseline.packMeta.gameVersion)};`);
L.push(`    public const string Loader = ${cs(baseline.packMeta && baseline.packMeta.loader)};`);
L.push('');
L.push('    /// <summary>detect() 的汇总。</summary>');
L.push(`    public const bool DetectFound = ${csBool(baseline.detect && baseline.detect.found)};`);
L.push(`    public const int RootCount = ${(baseline.detect && baseline.detect.rootCount) || 0};`);
L.push(`    public const int FolderCount = ${(baseline.detect && baseline.detect.folderCount) || 0};`);
L.push('');
L.push('    /// <summary>探测到的游戏文件夹（顺序即基准顺序）。</summary>');
L.push('    public static readonly RealFolder[] Folders =');
L.push('    [');
for (const f of baseline.folders) {
  L.push(`        new(${cs(f.name)}, ${cs(f.path)}, ${cs(f.source)}, ${csBool(f.isSelected)}),`);
}
L.push('    ];');
L.push('');
L.push('    /// <summary>scanAll() 的全部版本（顺序即基准顺序）。</summary>');
L.push('    public static readonly RealVersion[] Versions =');
L.push('    [');
for (const v of baseline.versions) {
  L.push(
    `        new(${cs(v.name)}, ${cs(v.folderName)}, ${cs(v.folderPath)}, ${cs(v.contentDir)}, ` +
    `${csBool(v.isolated)}, ${cs(v.isolationBasis)}, ${csNullable(v.gameVersion)}, ` +
    `${csNullable(v.loader)}, ${csNullable(v.loaderVersion)}, ${csBool(v.isSelected)}, ` +
    `${csBool(v.folderSelected)}, ${v.modCount}, ${csBool(v.managed)}),`);
}
L.push('    ];');
L.push('');
L.push('    /// <summary>matchTarget() 的排序结果（按分数降序）。</summary>');
L.push('    public static readonly RealRank[] Ranked =');
L.push('    [');
for (const r of baseline.ranked) {
  L.push(`        new(${cs(r.name)}, ${cs(r.folderName)}, ${cs(r.contentDir)}, ${r.score}, ${csArr(r.why.map(cs))}),`);
}
L.push('    ];');
L.push('');
L.push('    /// <summary>自动匹配到的目标；null 表示没匹配上。</summary>');
if (baseline.best) {
  L.push('    public static readonly RealRank? Best =');
  L.push(
    `        new(${cs(baseline.best.name)}, ${cs(baseline.best.folderName)}, ${cs(baseline.best.contentDir)}, ` +
    `${baseline.best.score}, ${csArr(baseline.best.why.map(cs))});`);
} else {
  L.push('    public static readonly RealRank? Best = null;');
}
L.push('}');
L.push('');

fs.writeFileSync(dest, L.join('\n'), 'utf8');
process.stderr.write(`已写入基准：folders=${baseline.folders.length} versions=${baseline.versions.length} ranked=${baseline.ranked.length}\n`);
